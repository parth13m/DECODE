import CoreGraphics
import Vision

/// Concrete implementation of ``OCRServiceProtocol`` using Apple Vision framework.
///
/// Uses `VNRecognizeTextRequest` with `.accurate` recognition level for
/// on-device text recognition. Optimized for code and technical content.
final class VisionOCRService: OCRServiceProtocol {

    func recognizeText(in image: CGImage) async throws -> String {
        try await withCheckedThrowingContinuation { continuation in
            let request = VNRecognizeTextRequest { request, error in
                if let error {
                    continuation.resume(throwing: error)
                    return
                }

                guard let observations = request.results as? [VNRecognizedTextObservation] else {
                    continuation.resume(returning: "")
                    return
                }

                let text = observations
                    .compactMap { $0.topCandidates(1).first?.string }
                    .joined(separator: "\n")

                continuation.resume(returning: text)
            }

            request.recognitionLevel = .accurate
            request.usesLanguageCorrection = false  // Preserve code tokens as-is

            let handler = VNImageRequestHandler(cgImage: image, options: [:])
            do {
                try handler.perform([request])
            } catch {
                continuation.resume(throwing: error)
            }
        }
    }
}
